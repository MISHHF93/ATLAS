"""Evo6 setup-variant research. Usage:
  ATLAS_FEED_DB=... PYTHONPATH=src python scripts/run_setup_variants.py [--procs 2] [--out docs/research/evo6-setup-variants]
Writes <out>.json and <out>.md (gross and net R per setup/symbol/interval/variant, bootstrap CIs, DSR, PBO, purged
walk-forward selection) and the per-trade rows to var/research/evo6_variant_rows.csv (never committed)."""
import argparse
import json
import os
from multiprocessing import Pool
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def job(args):
    sym, iv = args
    from atlas.feeds.feed import get_feed
    from atlas.research import setup_variants as SV
    sd = SV.load(get_feed(), sym, iv)
    if sd is None or len(sd.bars) < 200:
        return sym, iv, None, []
    rows = []
    for v in SV.VARIANTS:
        rows += SV.run_variant(sd, v)
    ds = {"symbol": sym, "interval": iv, "n_bars": len(sd.bars), "first_bar": sd.bars[0].start, "last_bar_end": sd.bars[-1].end,
          "providers": sd.providers, "sha256": sd.digest()}
    return sym, iv, ds, rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--procs", type=int, default=2)
    ap.add_argument("--out", default=str(root / "docs" / "research" / "evo6-setup-variants"))
    a = ap.parse_args()
    from atlas.research import setup_variants as SV
    jobs = [(s, i) for i in SV.INTERVALS for s in SV.SYMBOLS]
    with Pool(a.procs) as p:
        res = p.map(job, jobs)
    rows = [r for *_, rr in res for r in rr]
    datasets = [d for _, _, d, _ in res if d]
    ev = SV.evaluate(rows)
    ev["datasets"] = datasets
    ev["by_detector_variant_interval"] = SV.aggregate(rows, ("detector", "interval", "variant"))
    ev["by_variant"] = SV.aggregate(rows, ("variant",))
    ev["execution_permission"] = "none"
    out = Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(ev, indent=1, default=str))
    import pandas as pd
    vr = root / "var" / "research"; vr.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(vr / "evo6_variant_rows.csv", index=False)

    def f(x):
        return "-" if x is None else f"{x:+.3f}" if isinstance(x, float) else str(x)
    L = ["# Evo6 setup variants: gross vs net R (research evidence, not a performance claim)", "",
         "Generated by `scripts/run_setup_variants.py` from the local ATLAS feed (real bars), paper realism "
         "(1-bar latency, trade-through limits, 10% volume cap), venue costs from `atlas.ml.costs`. Ambiguous bars count as stops. "
         "Gross R = net R + cost R. 4h = complete UTC buckets of feed 1h bars (crypto only).", "",
         "## Variants", ""] + [f"- `{v.id}`: {v.description}" for v in SV.VARIANTS]
    L += ["", "## Data", "", "| symbol | interval | bars | first (UTC) | last end (UTC) |", "|---|---|---|---|---|"]
    from datetime import datetime, timezone
    iso = lambda t: datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d %H:%M")
    for d in datasets:
        L.append(f"| {d['symbol']} | {d['interval']} | {d['n_bars']} | {iso(d['first_bar'])} | {iso(d['last_bar_end'])} |")
    L += ["", "## By detector x interval x variant (all symbols pooled)", "",
          "| detector | interval | variant | n | win | gross R | net R | median cost R | net 95% CI |", "|---|---|---|---|---|---|---|---|---|"]
    for k, s in ev["by_detector_variant_interval"].items():
        det, iv, var = k.split("|")
        if s["n"]:
            L.append(f"| {det} | {iv} | {var} | {s['n']} | {f(s['win_rate'])} | {f(s['gross_r'])} | {f(s['net_r'])} | {f(s['median_cost_r'])} | [{f(s['net_ci95'][0])}, {f(s['net_ci95'][1])}] |")
    L += ["", "## Per symbol (configs with n >= 30)", "",
          "| symbol | interval | detector | variant | n | gross R | net R | net 95% CI | DSR | gates |", "|---|---|---|---|---|---|---|---|---|---|"]
    for c in ev["configs"]:
        if c["n"] >= 30:
            fails = [g["gate"] for g in c["gates"] if not g["passed"]]
            L.append(f"| {c['instrument']} | {c['interval']} | {c['detector']} | {c['variant']} | {c['n']} | {f(c['gross_r'])} | {f(c['net_r'])} | [{f(c['net_ci95'][0])}, {f(c['net_ci95'][1])}] | {f(c['dsr'])} | {'PASS' if c['passes_gates'] else 'FAIL: ' + ', '.join(fails)} |")
    pb = ev.get("pbo") or {}
    L += ["", f"Trials: {ev['n_trials']} configs. PBO (CSCV, 16 blocks, daily R): {pb.get('pbo')}", "",
          "## Purged walk-forward selection (1-day embargo; pick best TRAIN net R config per detector, score on TEST)", "",
          "| detector | n OOS | OOS gross R | OOS net R | net 95% CI | selections |", "|---|---|---|---|---|---|"]
    for det, w in ev["walk_forward_selection"].items():
        sel = ", ".join(sorted({p["selected"].split("|", 1)[1] if False else p["selected"] for p in w.get("folds", [])}))
        L.append(f"| {det} | {w.get('n_oos')} | {f(w.get('oos_gross_r'))} | {f(w.get('oos_net_r'))} | {w.get('oos_net_ci95')} | {sel} |")
    n_pass = sum(c["passes_gates"] for c in ev["configs"])
    L += ["", f"Configs passing all gates: {n_pass}. Execution permission: none.", ""]
    out.with_suffix(".md").write_text("\n".join(L) + "\n")
    print(json.dumps({"n_rows": len(rows), "n_trials": ev["n_trials"], "pbo": pb.get("pbo"), "n_pass": n_pass,
                      "by_variant": ev["by_variant"]}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
