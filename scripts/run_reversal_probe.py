"""Evo7 prior_day_range_reversal probe. Usage:
  ATLAS_FEED_DB=... PYTHONPATH=src python scripts/run_reversal_probe.py [--procs 2] [--out docs/research/evo7-reversal-probe]
Writes <out>.json and <out>.md; per-trade rows go to var/research/evo7_probe_rows.csv (never committed)."""
import argparse
import json
from datetime import datetime, timezone
from multiprocessing import Pool
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def jobs():
    from atlas.research import reversal_probe as P
    out = []
    for iv in ("4h", "1h"):
        out += [(s, iv, "crypto_core") for s in P.CRYPTO_CORE] + [(s, iv, "crypto_alts") for s in P.CRYPTO_ALTS]
    out += [(s, "1h", "us_etf") for s in P.EQUITY]
    return out


def job(a):
    sym, iv, u = a
    from atlas.feeds.feed import get_feed
    from atlas.ml.dataset import load_series
    from atlas.research import reversal_probe as P
    try:
        sd = load_series(get_feed(), sym, iv)
    except Exception as e:  # noqa: BLE001 - missing instrument/interval is reported, not fatal
        return None, [], f"{sym} {iv}: {e}"
    if len(sd.bars) < 300:
        return None, [], f"{sym} {iv}: {len(sd.bars)} bars (<300), skipped"
    rows = P.run_series(sd, u)
    return {"symbol": sym, "interval": iv, "universe": u, "n_bars": len(sd.bars), "first_bar": sd.bars[0].start,
            "last_bar_end": sd.bars[-1].end, "providers": sd.providers, "sha256": sd.digest()}, rows, None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--procs", type=int, default=2)
    ap.add_argument("--out", default=str(root / "docs" / "research" / "evo7-reversal-probe"))
    a = ap.parse_args()
    from atlas.research import reversal_probe as P
    with Pool(a.procs) as p:
        res = p.map(job, jobs())
    rows = [r for _, rr, _ in res for r in rr]
    ev = P.evaluate(rows)
    ev["datasets"] = [d for d, _, _ in res if d]
    ev["skipped"] = [m for *_, m in res if m]
    # descriptive breakdown of every trial by symbol (not used for selection)
    out = Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(ev, indent=1, default=str))
    import pandas as pd
    vr = root / "var" / "research"; vr.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(vr / "evo7_probe_rows.csv", index=False)
    f = lambda x: "-" if x is None else f"{x:+.3f}" if isinstance(x, float) else str(x)
    iso = lambda t: datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d %H:%M")
    L = ["# Evo7 prior_day_range_reversal probe (research evidence, not a performance claim)", "",
         "Generated by `scripts/run_reversal_probe.py` from the local ATLAS feed (real bars). Detections = the unchanged live path "
         "(evo6 `atr2_rr2` replay); each candidate re-simulated under every grid cell (see `atlas.research.reversal_probe`). "
         "`maker_assumed` is a labelled cost ASSUMPTION (2 bp per resting-limit leg, 12 bp per taker leg), not a verified fill model. "
         "Every cell is a trial counted in DSR and PBO.", "", "## Data", "",
         "| universe | symbol | interval | bars | first (UTC) | last end (UTC) | providers |", "|---|---|---|---|---|---|---|"]
    for d in ev["datasets"]:
        L.append(f"| {d['universe']} | {d['symbol']} | {d['interval']} | {d['n_bars']} | {iso(d['first_bar'])} | {iso(d['last_bar_end'])} | {', '.join(d['providers'])} |")
    if ev["skipped"]:
        L += ["", "Skipped: " + "; ".join(ev["skipped"])]
    pb = ev.get("pbo") or {}
    n_pass = sum(c["passes_gates"] for c in ev["configs"])
    L += ["", f"Trials: {ev['n_trials']}. PBO (CSCV, 16 blocks, daily net R): {pb.get('pbo')}. Configs passing all gates: {n_pass}.", "",
          "## All trials (universe x interval x entry/exit/filter/cost)", "",
          "| universe | tf | config | n | win | gross R | gross 95% CI | net R | net 95% CI | med cost R | DSR | gates |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in sorted(ev["configs"], key=lambda c: (c["universe"], c["interval"], -(c.get("net_r") or -9))):
        if not c["n"]:
            continue
        fails = [g["gate"] for g in c["gates"] if not g["passed"]]
        L.append(f"| {c['universe']} | {c['interval']} | {c['config']} | {c['n']} | {f(c['win_rate'])} | {f(c['gross_r'])} | "
                 f"[{f(c['gross_ci95'][0])}, {f(c['gross_ci95'][1])}] | {f(c['net_r'])} | [{f(c['net_ci95'][0])}, {f(c['net_ci95'][1])}] | "
                 f"{f(c['median_cost_r'])} | {f(c['dsr'])} | {'PASS' if c['passes_gates'] else 'FAIL: ' + ', '.join(fails)} |")
    L += ["", "## Purged walk-forward selection (5 folds, 1-day embargo; best TRAIN net R cell per universe/tf, scored on TEST)", "",
          "| universe/tf | n OOS | OOS gross R | OOS net R | OOS net 95% CI | selections |", "|---|---|---|---|---|---|"]
    for k, w in ev["walk_forward_selection"].items():
        sel = ", ".join(sorted({p["selected"].split("|")[-1] for p in w.get("folds", [])}))
        L.append(f"| {k} | {w.get('n_oos')} | {f(w.get('oos_gross_r'))} | {f(w.get('oos_net_r'))} | {w.get('oos_net_ci95')} | {sel} |")
    L += ["", "Execution permission: none.", ""]
    out.with_suffix(".md").write_text("\n".join(L) + "\n")
    print(json.dumps({"n_rows": len(rows), "n_trials": ev["n_trials"], "pbo": pb.get("pbo"), "n_pass": n_pass, "skipped": ev["skipped"]}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
