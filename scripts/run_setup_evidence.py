"""Run atlas.research.setup_evidence on var/evidence_cache and write docs/spec/evidence/ (JSON + Markdown)."""
import json
import sys
from pathlib import Path

from atlas.research.setup_evidence import registry_gates, run

root = Path(__file__).resolve().parents[1]
tag = sys.argv[1] if len(sys.argv) > 1 else "run"
# Prefer the authoritative ATLAS feed store; fall back to the legacy JSON cache. Override with argv[2].
_feed = root / "var" / "feeds" / "atlas_feed.sqlite"
src = Path(sys.argv[2]) if len(sys.argv) > 2 else (_feed if _feed.exists() else root / "var" / "evidence_cache")
r = run(src)
for c in r["configs"]:
    c["gates"] = registry_gates(c, r["pbo"])
    c["passes_offline_gates"] = all(g["passed"] for g in c["gates"] if g["gate"] != "shadow_weeks")
out = root / "docs" / "spec" / "evidence"
out.mkdir(parents=True, exist_ok=True)
(out / f"price-action-setups-{tag}.json").write_text(json.dumps(r, indent=1, default=str))
L = [f"# Price-action setup evidence ({tag})", "",
     "Real public data only. Research evidence, not a performance claim. Generated by `scripts/run_setup_evidence.py`.", "",
     "## Data", "", "| symbol | interval | source | first bar (UTC) | last bar (UTC) | bars | session |", "|---|---|---|---|---|---|---|"]
for d in r["datasets"]:
    L.append(f"| {d['symbol']} | {d['interval']} | {d['source']} | {d['first_bar_utc']} | {d['last_bar_utc']} | {d['n_bars']} | {d['session']} |")
L += ["", "## Method", ""] + [f"- **{k}**: {v}" for k, v in r["method"].items()]
L += ["", f"Trials counted for DSR: {r['n_trials']} (each config x {{take_all, ev_gate}}).", "",
      "## Out-of-sample results (pooled walk-forward test folds)", "",
      "| instrument | tf | detector | n_oos | base rate | Brier model / base | skill | log-loss model / base | mean R all (after cost) | EV-gate n / mean R | DSR (ev_gate) | offline gates |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for c in r["configs"]:
    if not c.get("n_oos"):
        L.append(f"| {c['instrument']} | {c['interval']} | {c['detector']} | 0 | - | - | - | - | - | - | - | FAIL (no OOS) |"); continue
    d = c["dsr"]["r_gate"]["dsr"]
    fails = [g["gate"] for g in c["gates"] if not g["passed"] and g["gate"] != "shadow_weeks"]
    L.append(f"| {c['instrument']} | {c['interval']} | {c['detector']} | {c['n_oos']} | {c['oos_base_rate']} | {c['brier_model']} / {c['brier_baseline']} | {c['brier_skill']} | {c['logloss_model']} / {c['logloss_baseline']} | {c['mean_r_all_after_cost']} | {c['n_taken_ev_gate']} / {c['mean_r_ev_gate_after_cost']} | {d:.4f} | {'PASS' if not fails else 'FAIL: ' + ', '.join(fails)} |")
L += ["", "## PBO (CSCV, 16 blocks)", ""]
for k, v in r["pbo"].items():
    L.append(f"- {k}: PBO = {v['pbo']:.3f} over {v['n_configs']} configs, {v['n_buckets']} buckets of {v['bucket_seconds']}s")
passed = [c for c in r["configs"] if c["passes_offline_gates"]]
L += ["", "## Registration decision", "",
      ("No detector passed the offline gates, so **no model was registered**. `DEFAULT_REGISTRY` stays empty and every live candidate keeps abstaining with `no_validated_model`."
       if not passed else f"{len(passed)} configs passed the offline gates. They still need shadow weeks before any promotion."), ""]
L += ["## Caveats", "",
      "- Yahoo 1h RTH bars start at :30; the 15:30 ET bar covers only 30 minutes but is treated as 1h, so detection times on it are later than the true bar end (conservative).",
      "- Yahoo daily OHLC is split-adjusted but not dividend-adjusted, and has no survivorship issue for these ETFs. Only the free-tier windows were available: 730 days of 1h data, and 1d data from inception.",
      "- Stooq was tried, but from this box it serves an HTML/JS challenge instead of CSV, so it was not used. `api.binance.com` is geo-restricted from this box; `data-api.binance.vision` (the same public klines) was used instead.",
      "- The fill model works on bars only (`conservative_ohlc_v1`); ambiguous bars count as stops. Costs are modelled assumptions, not measured fills.",
      "- The zone detectors have no live candidate rule. They were evaluated with the research mapping `zone_entry_v1` (entry at the confirmation close, stop at the far zone bound, target at 2R).",
      "- Several configs have small n (under 100 OOS), and their metrics are noisy.", ""]
(out / f"price-action-setups-{tag}.md").write_text("\n".join(L) + "\n")
print("\n".join(L[-3:]))
