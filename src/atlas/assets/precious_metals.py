def normalize_metal_price(
    price_per_troy_oz_usd: float | None,
    *,
    usd_cad_rate: float | None = None,
    premium_bps: float = 0.0,
) -> dict[str, float | None]:
    """Convert a per-troy-ounce USD metal price into troy oz, gram, and kilogram in both USD and CAD."""
    if price_per_troy_oz_usd is None or price_per_troy_oz_usd <= 0:
        return {
            "usd_per_troy_oz": None,
            "usd_per_gram": None,
            "usd_per_kilogram": None,
            "cad_per_troy_oz": None,
            "cad_per_gram": None,
            "cad_per_kilogram": None,
            "usd_with_estimated_premium_per_troy_oz": None,
            "cad_with_estimated_premium_per_troy_oz": None,
        }
    mult = 1.0 + (premium_bps / 10_000.0)
    usd_oz = round(price_per_troy_oz_usd, 2)
    usd_g = round(price_per_troy_oz_usd / TROY_OZ_TO_GRAMS, 2)
    usd_kg = round(price_per_troy_oz_usd * KG_TO_TROY_OZ, 2)
    usd_prem = round(price_per_troy_oz_usd * mult, 2)

    if usd_cad_rate and usd_cad_rate > 0:
        cad_oz = round(price_per_troy_oz_usd * usd_cad_rate, 2)
        cad_g = round((price_per_troy_oz_usd * usd_cad_rate) / TROY_OZ_TO_GRAMS, 2)
        cad_kg = round((price_per_troy_oz_usd * usd_cad_rate) * KG_TO_TROY_OZ, 2)
        cad_prem = round((price_per_troy_oz_usd * mult) * usd_cad_rate, 2)
    else:
        cad_oz = cad_g = cad_kg = cad_prem = None

    return {
        "usd_per_troy_oz": usd_oz,
        "usd_per_gram": usd_g,
        "usd_per_kilogram": usd_kg,
        "cad_per_troy_oz": cad_oz,
        "cad_per_gram": cad_g,
        "cad_per_kilogram": cad_kg,
        "usd_with_estimated_premium_per_troy_oz": usd_prem,
        "cad_with_estimated_premium_per_troy_oz": cad_prem,
    }


def build_precious_metals_catalog(
    *,
    metal: str | None = None,
    holding_form: str | None = None,
    now: float | None = None,
) -> dict[str, Any]:
    """Return the complete Feature (2) Precious Metals Catalog enriched with live feed quotes and unit/currency normalization."""
    from atlas.api.feeds_api import feed_quotes

    now_ts = float(now or time.time())
    quotes = feed_quotes(["GC", "MGC", "SI", "GLD", "SLV", "USD_CAD"], now_ts)
    usd_cad = (quotes.get("USD_CAD") or {}).get("price")

    items = []
    for spec in PRECIOUS_METAL_INSTRUMENTS:
        if metal and spec.metal != metal.strip().lower():
            continue
        if holding_form and spec.holding_form != holding_form.strip().lower():
            continue

        q_direct = quotes.get(spec.feed_symbol) if spec.feed_symbol else None
        q_spot = quotes.get(spec.spot_benchmark_feed_symbol) if spec.spot_benchmark_feed_symbol else None
        spot_oz_usd = float(q_spot["price"]) if (q_spot and q_spot.get("price")) else None
        direct_price = float(q_direct["price"]) if (q_direct and q_direct.get("price")) else None

        normalized = normalize_metal_price(
            spot_oz_usd,
            usd_cad_rate=float(usd_cad) if usd_cad else None,
            premium_bps=spec.typical_premium_over_spot_bps,
        )

        items.append({
            **spec.as_dict(),
            "market_price": direct_price if spec.holding_form in ("futures_contract", "exchange_traded_product", "spot_reference") else None,
            "spot_reference_usd_per_troy_oz": spot_oz_usd,
            "quote_status": (q_direct.get("status") if q_direct else "reference_only"),
            "quote_source": (q_direct.get("source") if q_direct else None),
            "quote_time_toronto": (q_direct.get("observed_at_toronto") if q_direct else None),
            "usd_cad_fx_rate": usd_cad,
            "normalized_units": normalized,
        })

    return {
        "feature_id": "feature_02_precious_metals_catalog",
        "count": len(items),
        "supported_metals": ["gold", "silver", "platinum", "palladium"],
        "supported_holding_forms": [
            "spot_reference",
            "physical_bullion",
            "allocated_holding",
            "unallocated_holding",
            "certificate_etr",
            "futures_contract",
            "exchange_traded_product",
        ],
        "unit_conversions": {
            "troy_oz_to_grams": TROY_OZ_TO_GRAMS,
            "kilogram_to_troy_oz": KG_TO_TROY_OZ,
        },
        "usd_cad_reference": {
            "rate": usd_cad,
            "source": (quotes.get("USD_CAD") or {}).get("source"),
            "observed_at_toronto": (quotes.get("USD_CAD") or {}).get("observed_at_toronto"),
        },
        "instruments": items,
        "execution_permission": EXECUTION_PERMISSION,
    }

