"""Feature (2): Precious Metals Catalog (`src/atlas/assets/precious_metals.py`).

Supports Gold (XAU), Silver (XAG), Platinum (XPT), and Palladium (XPD), explicitly distinguishing:
1. `spot_reference` — Interbank / LBMA / COMEX benchmark spot reference rates
2. `physical_bullion` — LBMA Good Delivery wholesale bars and Royal Canadian Mint Maple Leaf sovereign coins
3. `allocated_holding` — Segregated serial-numbered bars held under legal bailment custody
4. `unallocated_holding` — General unsecured creditor metal accounts (with explicit counterparty credit disclosure)
5. `certificate_etr` — Exchange-Traded Receipts (Royal Canadian Mint MNT.TO / MNS.TO) and Closed-End Physical Trusts (Sprott PHYS / PSLV / SPPP)
6. `futures_contract` — Regulated CME Group (COMEX / NYMEX) clearinghouse-margined futures (`GC`, `MGC`, `SI`, `PL`, `PA`)
7. `exchange_traded_product` — Open-end physical grantor trust ETPs (`GLD`, `IAU`, `SLV`, `PPLT`, `PALL`)

All prices are grounded in `atlas_feed` where stored (`GC`, `MGC`, `SI`, `GLD`, `SLV`, `USD_CAD`); instruments without a stored
feed print report `market_price: None` and `quote_status: "reference_only"` — never a fabricated quote.
"""
