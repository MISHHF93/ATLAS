def supported() -> list[str]:
    return sorted(BODIES)


def generate(strategy_id: str, cost_per_contract: float = 0.0, slippage_ticks: int = 1) -> str:
    if strategy_id not in BODIES:
        raise KeyError(f"no Pine export for {strategy_id!r}; supported: {supported()}")
    return HEADER.format(sid=strategy_id, cost=cost_per_contract, slip=int(slippage_ticks)) + BODIES[strategy_id]


def lint(src: str) -> list[str]:
    """Cheap structural checks (no TradingView compiler is available offline)."""
    errs = []
    if not src.startswith("//@version=5"):
        errs.append("missing //@version=5 header")
    if "strategy(" not in src:
        errs.append("missing strategy() declaration")
    if src.count("(") != src.count(")"):
        errs.append("unbalanced parentheses")
    if "lookahead_on" in src and "[1]" not in src:
        errs.append("lookahead_on without [1] offset leaks future data")
    return errs


def backtest_stats(r_multiples: Iterable[float | None]) -> dict[str, Any]:
    r = [float(x) for x in r_multiples if x is not None]
    if not r:
        return {"n_trades": 0, "win_rate": None, "profit_factor": None, "max_drawdown_r": None, "total_r": None, "mean_r": None}
    wins, losses = [x for x in r if x > 0], [x for x in r if x < 0]
    eq = peak = dd = 0.0
    for x in r:
        eq += x; peak = max(peak, eq); dd = max(dd, peak - eq)
    return {"n_trades": len(r), "win_rate": len(wins) / len(r), "profit_factor": (sum(wins) / -sum(losses)) if losses else None,
            "max_drawdown_r": dd, "total_r": sum(r), "mean_r": sum(r) / len(r)}


def atlas_backtest(instrument: str, bars: Sequence, strategy_id: str) -> dict[str, Any]:
    """Run ATLAS's conservative paper replay and keep the trades of this strategy's detector."""
    from atlas.features.price_action.engine import EngineConfig
    from atlas.features.price_action.replay import paper_replay_config, replay
    if strategy_id not in DETECTOR:
        raise KeyError(strategy_id)
    if not bars:
        return {"strategy_id": strategy_id, "status": "no_data", **backtest_stats([])}
    res = replay(instrument, bars[0].duration, bars, engine_cfg=EngineConfig(), cfg=paper_replay_config(), data_label="real:atlas_feed")
    det = DETECTOR[strategy_id]
    trades = [t for t in res.trades if t.detector == det]
    return {"strategy_id": strategy_id, "detector": det, "status": "ok", "bars": len(bars), "candidates": len(trades),
            "fill_model": "conservative_ohlc_v1 + paper realism", **backtest_stats(t.r_multiple for t in trades),
            "note": "descriptive replay in R multiples after the replay's cost model; not a performance promise"}
