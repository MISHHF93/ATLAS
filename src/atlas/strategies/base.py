"""Strategy Base Class, Signal Contracts & Control-Plane Dispatch Interface (`src/atlas/strategies/base.py`).

Enforces ATLAS Architectural Invariants:
1. Strict AI & Strategy Air-Gap (`execution_permission: "none"`):
   Strategies only emit probabilistic `StrategySignal` intents and never execute trades directly.
2. Deterministic Control-Plane Authority:
   Every order intent generated by any strategy bot must be routed through
   `ActionableControlPlaneEngine` (`evaluate_trading_rules` / `submit_order`), which
   deterministically enforces the 4.0% daily loss limit, 8.0% trailing HWM drawdown floor,
   <=35% single-day profit consistency gate, 0.75% per-trade risk cap, and mandatory ATR/structure stops.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from datetime import datetime, timezone
from decimal import Decimal
from typing import Any, Literal, Sequence

from pydantic import Field, FiniteFloat, model_validator

from atlas.control.engine import (
    ActionableControlPlaneEngine,
    ActionableOrderDecision,
    ActionableOrderRequest,
)
from atlas.control.rules import (
    AccountRiskSnapshot,
    ProposedTradeCheck,
    RuleEvaluationReport,
    TradingRuleBook,
    evaluate_trading_rules,
)
from atlas.models.schemas import Probability, Record, Text


StrategyTrack = Literal["open_market", "competition", "both"]
SignalDirection = Literal["BUY", "SELL", "HOLD"]
ExecutionTactic = Literal["LIMIT", "MARKET", "ALMGREN_CHRISS", "TWAP", "LIMIT_POC", "IOC"]


class CandleBar(Record):
    """Normalized OHLCV bar input for strategy evaluation."""

    symbol: Text
    timestamp: datetime
    open: FiniteFloat = Field(gt=0)
    high: FiniteFloat = Field(gt=0)
    low: FiniteFloat = Field(gt=0)
    close: FiniteFloat = Field(gt=0)
    volume: FiniteFloat = Field(ge=0)


class OrderBookDepthSnapshot(Record):
    """Normalized L2 order book snapshot with Point of Control (POC) & Value Area levels."""

    symbol: Text
    timestamp: datetime
    best_bid: FiniteFloat = Field(gt=0)
    best_ask: FiniteFloat = Field(gt=0)
    poc_price: FiniteFloat = Field(gt=0)
    val_price: FiniteFloat = Field(gt=0)
    vah_price: FiniteFloat = Field(gt=0)
    bid_depth_top5: FiniteFloat = Field(ge=0, default=1000.0)
    ask_depth_top5: FiniteFloat = Field(ge=0, default=1000.0)
    spread_bps: FiniteFloat = Field(ge=0, default=1.5)


class MicrostructureMetrics(Record):
    """Real-time microstructure, funding, auction imbalance, and state telemetry."""

    vpin: Probability = 0.25
    ofi_value: FiniteFloat = 0.0
    ofi_zscore: FiniteFloat = 0.0
    price_consolidation_score: Probability = 0.5
    spot_price: FiniteFloat | None = None
    perp_price: FiniteFloat | None = None
    funding_rate_8h: FiniteFloat = 0.0
    funding_zscore: FiniteFloat = 0.0
    auction_imbalance_shares: FiniteFloat = 0.0
    auction_imbalance_zscore: FiniteFloat = 0.0
    auction_timestamp_et: str = "09:28"
    atr_bps: FiniteFloat = Field(gt=0, default=120.0)
    inventory_fraction: FiniteFloat = 0.0
    state_vector: tuple[float, ...] = ()


class StrategySignal(Record):
    """Immutable probabilistic trading intent emitted by a strategy bot or WhalePolicyModel.

    Always carries `execution_permission = "none"`. Cannot execute orders directly.
    """

    strategy_id: Text = "STRAT_BASE"
    symbol: Text
    direction: SignalDirection
    target_conviction: Probability = 0.75
    conviction: Probability = 0.75
    suggested_stop_loss: FiniteFloat = Field(ge=0)
    suggested_take_profit: FiniteFloat = Field(ge=0)
    execution_tactic: ExecutionTactic = "ALMGREN_CHRISS"
    reference_price: FiniteFloat = Field(gt=0, default=100.0)
    target_entry_price: FiniteFloat = Field(gt=0, default=100.0)
    secondary_leg_symbol: str | None = None
    secondary_leg_direction: SignalDirection | None = None
    time_decay_exit_et: str | None = None
    rationale: str = ""
    telemetry: dict[str, Any] = Field(default_factory=dict)
    execution_permission: Literal["none"] = "none"

    @model_validator(mode="before")
    @classmethod
    def _sync_alias_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            d = dict(data)
            if "conviction" in d and "target_conviction" not in d:
                d["target_conviction"] = d["conviction"]
            elif "target_conviction" in d and "conviction" not in d:
                d["conviction"] = d["target_conviction"]

            if "target_entry_price" in d and "reference_price" not in d:
                d["reference_price"] = d["target_entry_price"]
            elif "reference_price" in d and "target_entry_price" not in d:
                d["target_entry_price"] = d["reference_price"]
            return d
        return data

    @model_validator(mode="after")
    def _enforce_air_gap(self) -> StrategySignal:
        if self.execution_permission != "none":
            raise ValueError("StrategySignal must strictly enforce execution_permission='none'")
        return self


class BaseStrategy(ABC):
    """Abstract base class for all ATLAS quantitative trading strategies."""

    strategy_id: str
    name: str
    track: StrategyTrack

    def __init__(
        self,
        *,
        strategy_id: str,
        name: str,
        track: StrategyTrack,
    ) -> None:
        self.strategy_id = strategy_id
        self.name = name
        self.track = track

    @abstractmethod
    def generate_signal(
        self,
        candle_batch: Sequence[CandleBar | dict[str, Any]],
        orderbook_depth: OrderBookDepthSnapshot | dict[str, Any],
        microstructure_metrics: MicrostructureMetrics | dict[str, Any],
    ) -> StrategySignal:
        """Evaluate point-in-time market data and return an air-gapped `StrategySignal`."""

    @staticmethod
    def _coerce_candles(candle_batch: Sequence[CandleBar | dict[str, Any]]) -> list[CandleBar]:
        normalized: list[CandleBar] = []
        for item in candle_batch:
            if isinstance(item, CandleBar):
                normalized.append(item)
            else:
                ts = item.get("timestamp") or datetime.now(timezone.utc)
                if isinstance(ts, str):
                    ts = datetime.fromisoformat(ts.replace("Z", "+00:00"))
                normalized.append(
                    CandleBar(
                        symbol=str(item.get("symbol", "SPY")),
                        timestamp=ts,
                        open=float(item.get("open", 100.0)),
                        high=float(item.get("high", 101.0)),
                        low=float(item.get("low", 99.0)),
                        close=float(item.get("close", 100.0)),
                        volume=float(item.get("volume", 1000.0)),
                    )
                )
        return normalized

    @staticmethod
    def _coerce_depth(
        orderbook_depth: OrderBookDepthSnapshot | dict[str, Any],
        default_symbol: str = "SPY",
        default_price: float = 100.0,
    ) -> OrderBookDepthSnapshot:
        if isinstance(orderbook_depth, OrderBookDepthSnapshot):
            return orderbook_depth
        ts = orderbook_depth.get("timestamp") or datetime.now(timezone.utc)
        if isinstance(ts, str):
            ts = datetime.fromisoformat(ts.replace("Z", "+00:00"))
        mid = float(orderbook_depth.get("poc_price", default_price))
        return OrderBookDepthSnapshot(
            symbol=str(orderbook_depth.get("symbol", default_symbol)),
            timestamp=ts,
            best_bid=float(orderbook_depth.get("best_bid", mid * 0.9995)),
            best_ask=float(orderbook_depth.get("best_ask", mid * 1.0005)),
            poc_price=mid,
            val_price=float(orderbook_depth.get("val_price", mid * 0.992)),
            vah_price=float(orderbook_depth.get("vah_price", mid * 1.008)),
            bid_depth_top5=float(orderbook_depth.get("bid_depth_top5", 1000.0)),
            ask_depth_top5=float(orderbook_depth.get("ask_depth_top5", 1000.0)),
            spread_bps=float(orderbook_depth.get("spread_bps", 1.5)),
        )

    @staticmethod
    def _coerce_metrics(
        microstructure_metrics: MicrostructureMetrics | dict[str, Any],
    ) -> MicrostructureMetrics:
        if isinstance(microstructure_metrics, MicrostructureMetrics):
            return microstructure_metrics
        return MicrostructureMetrics(**microstructure_metrics)

    def dispatch_to_control_plane(
        self,
        signal: StrategySignal,
        control_engine: ActionableControlPlaneEngine,
        *,
        target_track: Literal["competition", "open_market"] | None = None,
        desired_notional_usd: Decimal | None = None,
        stop_kind: Literal["atr", "structure"] = "atr",
        override_stop_distance_bps: Decimal | None = None,
        now: datetime | None = None,
    ) -> ActionableOrderDecision:
        """Route a `StrategySignal` through `ActionableControlPlaneEngine.submit_order()`.

        Only the deterministic control plane sizes, approves, or rejects the trade.
        """
        return dispatch_signal_to_control_plane(
            signal=signal,
            control_engine=control_engine,
            target_track=target_track or ("open_market" if self.track == "open_market" else "competition"),
            desired_notional_usd=desired_notional_usd,
            stop_kind=stop_kind,
            override_stop_distance_bps=override_stop_distance_bps,
            now=now,
        )


def evaluate_signal_against_rulebook(
    signal: StrategySignal,
    rulebook: TradingRuleBook,
    account: AccountRiskSnapshot,
    *,
    desired_notional_usd: Decimal,
    stop_kind: Literal["atr", "structure", "none"] = "atr",
    override_stop_distance_bps: Decimal | None = None,
    vpin_toxicity: float = 0.0,
    evaluated_at: datetime | None = None,
) -> RuleEvaluationReport:
    """Directly evaluate a `StrategySignal` against `evaluate_trading_rules` (`src/atlas/control/rules.py`)."""
    if signal.execution_permission != "none":
        raise ValueError("StrategySignal must carry execution_permission='none'")

    if override_stop_distance_bps is not None:
        stop_bps = override_stop_distance_bps
    elif signal.suggested_stop_loss <= 0 or signal.reference_price <= 0:
        stop_bps = Decimal("0")
        stop_kind = "none"
    else:
        raw_bps = abs(signal.reference_price - signal.suggested_stop_loss) / signal.reference_price * 10_000.0
        stop_bps = Decimal(str(round(raw_bps, 2)))
        if stop_bps <= Decimal("0"):
            stop_kind = "none"

    instrument_prefix = "comp" if rulebook.track == "competition" else "open"
    instrument_id = f"{instrument_prefix}:{signal.symbol.lower()}:v1"
    session_state = "continuous_24_7" if rulebook.track == "competition" else "regular_open"

    candidate = ProposedTradeCheck(
        instrument_id=instrument_id,
        notional_usd=desired_notional_usd,
        stop_kind=stop_kind,
        stop_distance_bps=max(Decimal("0"), stop_bps),
        holding_horizon_seconds=14400,
        current_holding_seconds=0,
        session_state=session_state,
        data_quality="verified",
        data_age_seconds=15.0,
        license_verified=True,
        correlated_group_add_usd=(desired_notional_usd * Decimal("0.25")).quantize(Decimal("0.01")),
        sector_add_usd=(desired_notional_usd * Decimal("0.25")).quantize(Decimal("0.01")),
        vpin_toxicity=vpin_toxicity,
    )
    return evaluate_trading_rules(
        rulebook=rulebook,
        account=account,
        candidate=candidate,
        evaluated_at=evaluated_at or account.as_of,
    )


def dispatch_signal_to_control_plane(
    signal: StrategySignal,
    control_engine: ActionableControlPlaneEngine,
    *,
    target_track: Literal["competition", "open_market"] = "competition",
    desired_notional_usd: Decimal | None = None,
    stop_kind: Literal["atr", "structure"] = "atr",
    override_stop_distance_bps: Decimal | None = None,
    vpin_toxicity: float = 0.0,
    now: datetime | None = None,
) -> ActionableOrderDecision:
    """Convert a `StrategySignal` into an `ActionableOrderRequest` and evaluate via `ActionableControlPlaneEngine`."""
    ts = now or datetime.now(timezone.utc)
    if signal.execution_permission != "none":
        raise ValueError("StrategySignal violated air-gap: execution_permission must be 'none'")

    if override_stop_distance_bps is not None:
        stop_bps = override_stop_distance_bps
    elif signal.suggested_stop_loss <= 0 or signal.reference_price <= 0:
        stop_bps = Decimal("0")
    else:
        raw_bps = abs(signal.reference_price - signal.suggested_stop_loss) / signal.reference_price * 10_000.0
        stop_bps = Decimal(str(round(raw_bps, 2)))

    # Size notional conservatively by conviction if desired_notional_usd is not explicitly supplied
    if desired_notional_usd is None:
        base_cap = Decimal("30000") if target_track == "competition" else Decimal("25000")
        conviction_dec = Decimal(str(round(max(0.10, float(signal.target_conviction)), 4)))
        notional = (base_cap * conviction_dec).quantize(Decimal("0.01"))
    else:
        notional = desired_notional_usd

    side: Literal["buy", "sell"] = "sell" if signal.direction == "SELL" else "buy"
    prefix = "comp" if target_track == "competition" else "open"
    instrument_id = f"{prefix}:{signal.symbol.lower()}:v1"

    req = ActionableOrderRequest(
        track=target_track,
        instrument_id=instrument_id,
        side=side,
        notional_usd=notional,
        stop_kind=stop_kind,
        stop_distance_bps=max(Decimal("0"), stop_bps),
        holding_horizon_seconds=14400,
        vpin_toxicity=vpin_toxicity,
    )
    return control_engine.submit_order(req, now=ts)

